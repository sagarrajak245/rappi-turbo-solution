"""Scenario 1 decision graph, KB §3.2 nodes 1–10.

Deterministic nodes fetch, check and compute; the LLM only chooses and explains (D17). The
deterministic validator has the final say, and anything the validator or the reviewer rejects
goes back to `decide` with the issues, at most `llm.max_review_attempts` times, then ESCALATE.
Blocking or escalate data never reaches the LLM at all.

Graph nodes reach data only through the planning and validation services, never repositories.
The graph ends at `propose`; the human gate is the persisted run row (agent/service.py), so a
run needs no durable checkpointer and nothing before the gate has side effects.
"""

import json
from dataclasses import dataclass
from typing import Any

from langgraph.checkpoint.base import BaseCheckpointSaver
from langgraph.graph import END, START, StateGraph
from langgraph.graph.state import CompiledStateGraph
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from app.core.config import Settings
from app.modules.agent.llm.base import LlmClient, LlmUnavailable
from app.modules.agent.prompts import load_prompt
from app.modules.agent.schemas import DecisionOut, ProposalOut, ReviewOut
from app.modules.agent.state import AgentState
from app.modules.memory import service as memory
from app.modules.planning import service as planning
from app.modules.planning.schemas import CalcResult, Flag, PlanningInput
from app.modules.validation import service as validation
from app.modules.validation.schemas import ProposedDecision, ValidationResult
from app.shared.enums import FlagSeverity, Outcome, Verdict


@dataclass(frozen=True)
class GraphDeps:
    sessionmaker: async_sessionmaker[AsyncSession]
    decide_llm: LlmClient
    review_llm: LlmClient
    settings: Settings


# ---- pure helpers -------------------------------------------------------------------------


def _flag_fact(f: Flag) -> dict[str, str]:
    # Messages are generated by our own checks and never quote supplier/product notes (Q7).
    return {"code": f.code.value, "severity": f.severity.value, "message": f.message}


def facts(inp: PlanningInput, calc: CalcResult, flags: tuple[Flag, ...]) -> dict[str, Any]:
    """Everything the LLM may cite. Deliberately excludes supplier_notes and product_notes."""
    return {
        "sku": inp.sku,
        "node": inp.node,
        "recommended_qty": inp.rec_qty,
        "baseline": {
            "qty": calc.qty,
            "verdict": calc.verdict.value if calc.verdict else None,
            "outcome": calc.outcome.value,
        },
        "need_qty": calc.need_qty,
        "protection_days": calc.protection_days,
        "demand_daily": round(calc.demand_daily, 2),
        "demand_source": calc.demand_source,
        "demand_over_protection": round(calc.demand_over_p, 2),
        "safety_stock": calc.safety_stock,
        "inventory_position": calc.inventory_position,
        "stock_at_arrival": round(calc.stock_at_arrival, 2),
        "cover_days": None if calc.cover_days is None else round(calc.cover_days, 1),
        "caps": {code.value: cap for code, cap in calc.caps.items()},
        "moq": inp.moq,
        "case_pack": inp.case_pack,
        "lead_time_days": inp.lead_time_days,
        "unit_cost_inr": str(inp.unit_cost_inr),
        "budget_remaining_inr": str(inp.budget_remaining_inr),
        "flags": [_flag_fact(f) for f in flags + calc.flags],
        "options": [o.model_dump(mode="json") for o in calc.options],
    }


def validation_feedback(v: ValidationResult) -> list[str]:
    out = list(v.issues)
    out += [f"{x.code.value}: {x.message}" for x in v.violations]
    out += [
        f"{b.policy}: {b.message} (override it with a reason or change the qty)"
        for b in v.soft_breaches
    ]
    if v.suggestions:
        out.append(f"nearest valid quantities: {', '.join(map(str, v.suggestions))}")
    return out


def _forced_decision(flags: tuple[Flag, ...], calc: CalcResult) -> ProposedDecision | None:
    """Data the LLM must not decide on: blocking -> INVESTIGATE, escalate -> ESCALATE."""
    severities = {f.severity for f in flags}
    if FlagSeverity.BLOCKING in severities:
        return ProposedDecision(
            verdict=Verdict.INVESTIGATE, qty=None, reasons=("data quality blocks a decision",)
        )
    if FlagSeverity.ESCALATE in severities or calc.outcome is Outcome.ESCALATE:
        return ProposedDecision(
            verdict=None,
            qty=None,
            outcome=Outcome.ESCALATE,
            reasons=("no valid purchase order under the current constraints",),
        )
    return None


# ---- graph ------------------------------------------------------------------------------


def human_verdict(qty: int, rec_qty: int) -> Verdict:
    """The verdict a buyer's own quantity implies (0 = reject, rec = accept, else modify)."""
    return Verdict.REJECT if qty == 0 else Verdict.ACCEPT if qty == rec_qty else Verdict.MODIFY


def build_graph(
    deps: GraphDeps, checkpointer: BaseCheckpointSaver[Any] | None = None
) -> CompiledStateGraph[AgentState, Any, AgentState, AgentState]:
    s = deps.settings
    max_attempts = s.llm.max_review_attempts

    async def load_context(state: AgentState) -> AgentState:
        async with deps.sessionmaker() as session:
            inp = await planning.load_planning_input(
                session, state["sku"], state["node"], state["today"], settings=s.planning
            )
        return {"inp": inp, "attempts": 0, "llm_records": [], "feedback": []}

    async def data_quality(state: AgentState) -> AgentState:
        return {"flags": validation.check_data_quality(state["inp"], state["now"], s.data_quality)}

    async def compute(state: AgentState) -> AgentState:
        calc = planning.calculate(state["inp"], s.planning)
        return {"calc": calc, "baseline": validation.baseline_decision(calc)}

    async def recall_memory(state: AgentState) -> AgentState:
        # Active lessons the buyer confirmed for this SKU x node (D25); soft guidance only.
        async with deps.sessionmaker() as session:
            found = await memory.active_for(session, state["sku"], state["node"])
        return {"lessons": [x.text for x in found], "lesson_ids": [x.id for x in found]}

    async def deterministic(state: AgentState) -> AgentState:
        decision = _forced_decision(state["flags"], state["calc"])
        assert decision is not None  # routed here only when forced
        return {"decision": decision, "skip_llm": True}

    async def decide(state: AgentState) -> AgentState:
        payload: dict[str, Any] = {"FACTS": facts(state["inp"], state["calc"], state["flags"])}
        if state.get("feedback"):
            payload["FEEDBACK"] = state["feedback"]
        if state.get("lessons"):
            payload["LESSONS"] = state["lessons"]
        attempts = state.get("attempts", 0) + 1
        try:
            out, record = await deps.decide_llm.complete_json(
                load_prompt("decide"), json.dumps(payload), DecisionOut
            )
        except LlmUnavailable as exc:
            return {"attempts": attempts, "escalate_reason": f"decision model failed: {exc}"}
        return {
            "decision_out": out,
            "decision": out.to_proposed(),
            "attempts": attempts,
            "llm_records": [*state.get("llm_records", []), record],
        }

    async def validate(state: AgentState) -> AgentState:
        v = validation.validate(
            state["decision"], state["inp"], state["calc"], tuple(state["flags"]), s.planning
        )
        return {"validation": v, "feedback": [] if v.valid else validation_feedback(v)}

    async def review(state: AgentState) -> AgentState:
        payload = {
            "FACTS": facts(state["inp"], state["calc"], state["flags"]),
            "DECISION": state["decision_out"].model_dump(mode="json"),
            "VALIDATION": state["validation"].model_dump(mode="json"),
        }
        try:
            out, record = await deps.review_llm.complete_json(
                load_prompt("review"), json.dumps(payload), ReviewOut
            )
        except LlmUnavailable as exc:
            return {"review_ok": False, "escalate_reason": f"review model failed: {exc}"}
        issues = out.issues or ["reviewer rejected the decision without details"]
        return {
            "review_ok": out.ok,
            "feedback": [] if out.ok else [f"reviewer: {i}" for i in issues],
            "llm_records": [*state.get("llm_records", []), record],
        }

    async def escalate(state: AgentState) -> AgentState:
        reason = state.get("escalate_reason") or (
            f"no valid decision after {state.get('attempts', 0)} attempts: "
            + "; ".join(state.get("feedback", []))
        )
        decision = ProposedDecision(
            verdict=None, qty=None, outcome=Outcome.ESCALATE, reasons=(reason,)
        )
        v = validation.validate(decision, state["inp"], state["calc"], (), s.planning)
        return {"decision": decision, "validation": v, "escalate_reason": reason}

    async def propose(state: AgentState) -> AgentState:
        d, v, calc = state["decision"], state["validation"], state["calc"]
        issues = list(v.issues) + [x.message for x in v.violations]
        if state.get("escalate_reason"):
            issues.append(state["escalate_reason"])
        proposal = ProposalOut(
            thread_id=state["thread_id"],
            sku=state["sku"],
            node=state["node"],
            rec_qty=state["inp"].rec_qty,
            baseline_qty=calc.qty,
            verdict=v.verdict,
            qty=v.qty,
            outcome=v.outcome,
            valid=v.valid,
            reasons=list(d.reasons),
            deviation_reason=d.deviation_reason,
            flags=list(v.flags),
            options=list(calc.options) if v.outcome is Outcome.ESCALATE else [],
            issues=issues,
            suggestions=list(v.suggestions),
            attempts=state.get("attempts", 0),
            llm_calls=len(state.get("llm_records", [])),
            lessons_applied=state.get("lesson_ids", []) if not state.get("skip_llm") else [],
        )
        return {"proposal": proposal}

    # ---- routing ----

    def after_recall(state: AgentState) -> str:
        forced = _forced_decision(state["flags"], state["calc"])
        return "deterministic" if forced is not None else "decide"

    def after_decide(state: AgentState) -> str:
        return "escalate" if state.get("escalate_reason") else "validate"

    def retry_or_escalate(state: AgentState) -> str:
        return "decide" if state.get("attempts", 0) < max_attempts else "escalate"

    def after_validate(state: AgentState) -> str:
        if state.get("skip_llm"):
            return "propose"
        return "review" if state["validation"].valid else retry_or_escalate(state)

    def after_review(state: AgentState) -> str:
        if state.get("escalate_reason"):
            return "escalate"
        return "propose" if state.get("review_ok") else retry_or_escalate(state)

    g: StateGraph[AgentState, Any, AgentState, AgentState] = StateGraph(AgentState)
    g.add_node("load_context", load_context)
    g.add_node("data_quality", data_quality)
    g.add_node("compute", compute)
    g.add_node("recall_memory", recall_memory)
    g.add_node("deterministic", deterministic)
    g.add_node("decide", decide)
    g.add_node("validate", validate)
    g.add_node("review", review)
    g.add_node("escalate", escalate)
    g.add_node("propose", propose)
    g.add_edge(START, "load_context")
    g.add_edge("load_context", "data_quality")
    g.add_edge("data_quality", "compute")
    g.add_edge("compute", "recall_memory")
    g.add_conditional_edges("recall_memory", after_recall, ["deterministic", "decide"])
    g.add_edge("deterministic", "validate")
    g.add_conditional_edges("decide", after_decide, ["validate", "escalate"])
    g.add_conditional_edges("validate", after_validate, ["propose", "review", "decide", "escalate"])
    g.add_conditional_edges("review", after_review, ["propose", "decide", "escalate"])
    g.add_edge("escalate", "propose")
    g.add_edge("propose", END)
    return g.compile(checkpointer=checkpointer)
